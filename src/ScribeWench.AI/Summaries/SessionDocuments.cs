using System.Text;
using System.Text.RegularExpressions;
using ScribeWench.AI.Notes;
using ScribeWench.Core.Models;

namespace ScribeWench.AI.Summaries;

// A summary as the files and messages it becomes.
public static class SessionDocuments
{
    // Heads the list of what the recording changed in the game's other notes. ScribeWench adds it, last.
    public const string ChangesHeading = "## What Changed";

    // The tags that tell the two kinds of note in the sessions folder apart.
    public const string SessionTag = "session";
    public const string DiscussionTag = "discussion";

    private static readonly Regex ChangesRegex = new(
        @"^\#\#\s*What Changed[ \t]*\r?$(?<body>.*?)(?=^\#\#\s|\z)",
        RegexOptions.Multiline | RegexOptions.Singleline | RegexOptions.IgnoreCase | RegexOptions.Compiled);

    // For the output folder and for Discord.
    public static string Plain(SummaryResult summary, SummarizationOptions options, string aiLabel, IReadOnlyList<string>? changes = null) =>
        $"# {options.CampaignName} — {options.SessionDateTime:yyyy-MM-dd HH:mm}\n" +
        $"> *Generated by ScribeWench using {aiLabel}*\n\n" +
        WithChanges(Body(summary), changes) + "\n";

    public static string ObsidianNote(SummaryResult summary, SummarizationOptions options, string aiLabel, IReadOnlyList<string>? changes = null) =>
        Frontmatter(options, aiLabel, SessionTag) + WithChanges(summary.Markdown, changes) + "\n";

    // Opens with what the discussion was about, in the model's one sentence. A short one is only
    // that and the list of what changed.
    public static string DiscussionNote(SummaryResult summary, SummarizationOptions options, string aiLabel, IReadOnlyList<string>? changes = null) =>
        Frontmatter(options, aiLabel, DiscussionTag) + WithChanges(summary.Reason + "\n\n" + summary.Markdown.Trim(), changes) + "\n";

    public static string ForDiscord(SummaryResult summary, SummarizationOptions options, string aiLabel, IReadOnlyList<string>? changes = null) =>
        StripWikiLinks(Plain(summary, options, aiLabel, changes));

    // The recording as text: the session note, or what it was instead, with the discussion note if one was written.
    public static string Body(SummaryResult summary) => summary.Kind switch
    {
        RecordingKind.Discussion => ($"**Campaign discussion, not a game session:** {summary.Reason}\n\n" + summary.Markdown.Trim()).Trim(),
        RecordingKind.Neither => $"**Not a game session:** {summary.Reason}",
        _ => summary.Markdown.Trim(),
    };

    // One line per change to what a note says, in the model's sentence, then the notes made and added to.
    public static IReadOnlyList<string> ChangeLines(VaultUpdates.Result notes)
    {
        var lines = notes.Changes.ToList();
        if (notes.Created.Count > 0) lines.Add("New notes: " + string.Join(", ", notes.Created.Select(n => $"[[{n}]]")));
        if (notes.Updated.Count > 0) lines.Add("Updated notes: " + string.Join(", ", notes.Updated.Select(n => $"[[{n}]]")));
        return lines;
    }

    // The lines of a note's own list, for carrying over when the note is written again.
    public static IReadOnlyList<string> ChangeLinesIn(string markdown) =>
        ChangesRegex.Match(markdown) is { Success: true } section
            ? section.Groups["body"].Value.Split('\n')
                .Select(l => l.Trim())
                .Where(l => l.StartsWith("- ", StringComparison.Ordinal))
                .Select(l => l[2..].Trim())
                .ToList()
            : [];

    // The model is told not to write the list, and it comes out again when it does anyway.
    public static string WithoutChanges(string markdown) =>
        ChangesRegex.IsMatch(markdown) ? ChangesRegex.Replace(markdown, "").TrimEnd() + "\n" : markdown;

    private static string WithChanges(string markdown, IReadOnlyList<string>? changes)
    {
        var text = WithoutChanges(markdown).Trim();
        if (changes is not { Count: > 0 }) return text;

        var sb = new StringBuilder(text);
        if (text.Length > 0) sb.Append("\n\n");
        sb.Append(ChangesHeading);
        foreach (var change in changes) sb.Append("\n- ").Append(change);
        return sb.ToString();
    }

    // [[Note]] → Note, [[Note|text]] → text, [[Note#Heading]] → Note.
    public static string StripWikiLinks(string markdown) =>
        Regex.Replace(
            markdown,
            @"!?\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|([^\]]+))?\]\]",
            m => m.Groups[2].Success ? m.Groups[2].Value : m.Groups[1].Value);

    private static string Frontmatter(SummarizationOptions options, string aiLabel, string tag) =>
        "---\n" +
        $"date: {options.SessionDateTime:yyyy-MM-dd}\n" +
        $"campaign: {YamlString(options.CampaignName)}\n" +
        $"tags:\n  - {tag}\n" +
        $"generated-by: {YamlString(aiLabel)}\n" +
        "---\n\n";

    private static string YamlString(string value) =>
        "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";
}
