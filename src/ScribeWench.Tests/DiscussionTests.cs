using ScribeWench.Core.Models;
using ScribeWench.Tests.Support;

namespace ScribeWench.Tests;

// A recording where the group talks about the campaign without playing.
public sealed class DiscussionTests : IDisposable
{
    private static readonly DateTime Recorded = new(2026, 11, 25, 20, 22, 0);
    private readonly string _root = Path.Combine(Path.GetTempPath(), "scribewench-tests", Guid.NewGuid().ToString("N"));
    private string Vault => Path.Combine(_root, "vault");
    private string Sessions => Path.Combine(Vault, "Runeterra", "Sessions");

    public DiscussionTests() => Directory.CreateDirectory(Vault);

    public void Dispose()
    {
        try { Directory.Delete(_root, recursive: true); } catch { }
    }

    private string WriteNote(string relativePath, string content)
    {
        var path = Path.Combine(Vault, relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content);
        return path;
    }

    private AppConfig Config() => new()
    {
        Ai = { PromptFile = Path.Combine(_root, "summary-prompt.md") },
        Obsidian = { VaultPath = Vault },
    };

    private static string Read(string path) => File.ReadAllText(path).ReplaceLineEndings("\n");

    private static readonly SessionDetails Details = new("Runeterra", Recorded, "Runeterra", "x");

    private const string Frontmatter =
        "---\ndate: 2026-11-25\ncampaign: \"Runeterra\"\ntags:\n  - discussion\ngenerated-by: \"a test\"\n---\n\n";

    private async Task<(SessionSummarizer Summarizer, SessionDraft Draft, SavedSession Saved)> RunAsync(string reply)
    {
        var summarizer = TestNotes.Summarizer(Config(), _root, reply);
        var draft = await summarizer.WriteAsync([], summarizer.Prepare(Details));
        return (summarizer, draft, await summarizer.SaveAsync(draft, Details));
    }

    [Fact]
    public async Task AShortOne_GetsANote_OfItsSentenceAndWhatChanged()
    {
        var tome = WriteNote("Runeterra/Items/Orfelt's tome.md", "A book.\n");

        var (summarizer, draft, saved) = await RunAsync(
            "CAMPAIGN_DISCUSSION: A clarification of how [[Orfelt's tome]] works.\n\n" +
            "## Cast Updates\n- None\n\n" +
            "## Vault Updates\n### [[Orfelt's tome]]\n- Holds every book in the [[Bandle City]] library.\n");

        // Beside the session notes, told apart by its name and its tag.
        Assert.Equal(Path.Combine(Sessions, "2026-11-25 Runeterra discussion.md"), saved.NotePath);
        Assert.Equal(
            Frontmatter +
            "A clarification of how [[Orfelt's tome]] works.\n\n" +
            "## What Changed\n- Updated notes: [[Orfelt's tome]]\n",
            Read(saved.NotePath!));
        Assert.Equal(
            "A book.\n\n## From the sessions\n\n- [[2026-11-25 Runeterra discussion]]: Holds every book in the [[Bandle City]] library.\n",
            Read(tome));

        Assert.Equal(
            "# Runeterra — 2026-11-25 20:22\n> *Generated by ScribeWench using a test*\n\n" +
            "**Campaign discussion, not a game session:** A clarification of how Orfelt's tome works.\n\n" +
            "## What Changed\n- Updated notes: Orfelt's tome\n",
            summarizer.ForDiscord(draft, saved));
    }

    [Fact]
    public async Task ALongOne_KeepsItsTopics_BetweenTheSentenceAndWhatChanged()
    {
        var vol = WriteNote("Runeterra/NPCs/Vol.md", "Vol rules the castle.\n");

        var (summarizer, draft, saved) = await RunAsync(
            "CAMPAIGN_DISCUSSION: Planning the heist and what became of Vol.\n\n" +
            "## The heist\n- Go in by the sewers.\n\n" +
            "## Cast Updates\n- **Ralkern** runs the game.\n\n" +
            "## Vault Updates\n### [[Vol]]\n- Lost the castle to his sister.\n" +
            "Changed: [[Vol]] no longer rules the castle\n<<<<<<< FIND\nVol rules the castle.\n=======\nVol ruled the castle until {session}.\n>>>>>>> END\n");

        Assert.Equal(
            Frontmatter +
            "Planning the heist and what became of Vol.\n\n" +
            "## The heist\n- Go in by the sewers.\n\n" +
            "## What Changed\n- [[Vol]] no longer rules the castle\n- Updated notes: [[Vol]]\n",
            Read(saved.NotePath!));
        Assert.Equal(
            "Vol ruled the castle until [[2026-11-25 Runeterra discussion]].\n\n" +
            "## From the sessions\n\n- [[2026-11-25 Runeterra discussion]]: Lost the castle to his sister.\n",
            Read(vol));
        Assert.Contains("- 2026-11-25: **Ralkern** runs the game.", Read(Path.Combine(Vault, "Runeterra", "Cast.md")));

        var post = summarizer.ForDiscord(draft, saved);
        Assert.Contains("**Campaign discussion, not a game session:** Planning the heist and what became of Vol.\n\n## The heist", post);
        Assert.EndsWith("## What Changed\n- Vol no longer rules the castle\n- Updated notes: Vol\n", post);
    }

    [Fact]
    public async Task OneOnTheDayOfASession_OrOfAnotherDiscussion_GetsItsOwnNote()
    {
        var session = WriteNote("Runeterra/Sessions/2026-11-25 Runeterra.md", "## What Happened\n\nA fight.\n");

        var (_, _, first) = await RunAsync("CAMPAIGN_DISCUSSION: Planning.\n\n## Plans\n- Wait a week.\n");
        var (_, _, second) = await RunAsync("CAMPAIGN_DISCUSSION: More planning.\n");

        Assert.Equal(Path.Combine(Sessions, "2026-11-25 Runeterra discussion.md"), first.NotePath);
        Assert.Equal(Path.Combine(Sessions, "2026-11-25 Runeterra discussion (2).md"), second.NotePath);
        Assert.Equal("## What Happened\n\nA fight.\n", Read(session));
    }

    [Fact]
    public async Task ARecordingThatIsNeither_WritesNothing()
    {
        var vol = WriteNote("Runeterra/NPCs/Vol.md", "Lord.\n");

        var (summarizer, draft, saved) = await RunAsync(
            "NOT_A_SESSION: A soundcheck.\n\n## Vault Updates\n### [[Vol]]\n- Sings.\n");

        Assert.Null(saved.NotePath);
        Assert.False(saved.Notes.Any);
        Assert.False(Directory.Exists(Sessions));
        Assert.Equal("Lord.\n", Read(vol));
        Assert.EndsWith("**Not a game session:** A soundcheck.\n", summarizer.ForDiscord(draft, saved));
    }

    [Fact]
    public void TheNextSession_ReadsItsNote_ButContinuesFromTheLastSessionPlayed()
    {
        WriteNote("Runeterra/Sessions/2026-11-22 Runeterra.md", "---\ntags:\n  - session\n---\n\n## What Happened\n\nA fight.\n");
        WriteNote("Runeterra/Sessions/2026-11-25 Runeterra discussion.md", Frontmatter + "Planning.\n\n## Plans\n- Wait a week.\n");

        var context = TestNotes.Summarizer(Config(), _root).Prepare(new SessionDetails("Runeterra", new DateTime(2026, 11, 29), "Runeterra", "x"));

        Assert.EndsWith("2026-11-22 Runeterra.md", context.Vault!.PreviousSessionPath);
        Assert.Contains("<note name=\"2026-11-22 Runeterra\" folder=\"Sessions\" previous-session=\"true\">", context.Options.Context);
        Assert.Contains("<note name=\"2026-11-25 Runeterra discussion\" folder=\"Sessions\" discussion=\"true\">\nPlanning.\n\n## Plans\n- Wait a week.", context.Options.Context!.ReplaceLineEndings("\n"));
        Assert.DoesNotContain("2026-11-25 Runeterra discussion", context.Options.PartContext);
    }

    [Fact]
    public void ADiscussionNote_IsKnownByItsTag_NotItsName()
    {
        var discussion = WriteNote("Runeterra/Sessions/2026-11-25 Runeterra discussion.md", Frontmatter + "Planning.\n");
        var session = WriteNote("Runeterra/Sessions/2026-11-22 Book discussion.md", "---\ntags: [session]\n---\n\nA session of a game called Book discussion.\n");

        Assert.True(ObsidianVault.IsDiscussionNote(discussion));
        Assert.False(ObsidianVault.IsDiscussionNote(session));
    }
}
